#pragma once
// Signal phases, the explicit conflict model, and the safety-enforcing signal
// state machine. Controllers only *propose* decisions; TrafficSignal enforces
// minimum green, yellow, all-red clearance and conflict freedom.

#include <optional>
#include <string>
#include <vector>

#include "traffic/core/config.hpp"
#include "traffic/network/road_network.hpp"

namespace traffic {

struct SignalPhase {
  std::string name;
  std::vector<MovementId> movements;  // vehicle movements that receive green
  std::vector<int> crosswalks;        // crosswalk indices that receive WALK
  double min_green = 7.0;
  double max_green = 60.0;
  double green = 20.0;  // default fixed-time green
  double yellow = 3.5;
  double all_red = 1.5;
  double walk_time = 0.0;      // 0 if the phase serves no crosswalk
  double ped_clearance = 0.0;  // flashing don't-walk interval after WALK

  [[nodiscard]] bool serves_vehicles() const { return !movements.empty(); }
  [[nodiscard]] bool contains(MovementId m) const;
  [[nodiscard]] bool contains_crosswalk(int c) const;
};

/// Pairwise conflict relations at one intersection. Two movements conflict if they
/// come from different approaches and either merge into the same outgoing road or
/// their connector paths cross. A crosswalk conflicts with every movement that
/// enters or leaves through the arm it crosses.
class ConflictModel {
 public:
  ConflictModel() = default;
  ConflictModel(const RoadNetwork& net, NodeId node);

  [[nodiscard]] NodeId node() const { return node_; }
  [[nodiscard]] const std::vector<MovementId>& movements() const { return movements_; }
  [[nodiscard]] int local(MovementId m) const;
  [[nodiscard]] bool conflicts(MovementId a, MovementId b) const;
  [[nodiscard]] bool crosswalk_conflicts(int crosswalk, MovementId m) const;
  [[nodiscard]] int crosswalk_count() const { return static_cast<int>(ped_.size()); }

 private:
  NodeId node_ = kInvalidNode;
  MovementId first_ = 0;
  std::vector<MovementId> movements_;
  std::vector<std::vector<bool>> conflict_;  // local x local
  std::vector<std::vector<bool>> ped_;       // crosswalk x local
};

struct PhasePlan {
  std::vector<SignalPhase> phases;
  std::vector<std::string> errors;
};

/// Builds phases for a node. With no explicit spec, phases are generated by greedy
/// graph colouring of the movement conflict graph followed by maximal augmentation;
/// crosswalks join every compatible phase, and crosswalks compatible with no phase
/// get an exclusive pedestrian phase.
PhasePlan build_phase_plan(const RoadNetwork& net, NodeId node, const ConflictModel& conflicts,
                           const SignalTimingSpec& timing, const PedestrianSpec& peds,
                           const IntersectionSignalSpec* explicit_spec);

/// Checks a phase set: no conflicting pair inside any phase, every movement served,
/// timing constraints consistent.
std::vector<std::string> validate_phase_plan(const RoadNetwork& net, NodeId node,
                                             const ConflictModel& conflicts,
                                             const std::vector<SignalPhase>& phases);

struct SignalDecision {
  bool switch_phase = false;
  int next_phase = -1;  // phase to serve after the change interval
};

class TrafficSignal {
 public:
  TrafficSignal(const RoadNetwork& net, NodeId node, std::vector<SignalPhase> phases);

  /// Advances the state machine by dt. `other_demand` tells the safety layer whether
  /// any other phase has demand; max-green is enforced only when it does.
  void step(double dt, const SignalDecision& decision, bool other_demand);

  [[nodiscard]] NodeId node() const { return node_; }
  [[nodiscard]] LightState movement_state(MovementId m) const;
  [[nodiscard]] WalkState crosswalk_state(int crosswalk) const;
  [[nodiscard]] int current_phase() const { return current_; }
  [[nodiscard]] int next_phase() const { return next_; }
  [[nodiscard]] SignalStage stage() const { return stage_; }
  [[nodiscard]] double time_in_stage() const { return t_stage_; }
  [[nodiscard]] const std::vector<SignalPhase>& phases() const { return phases_; }
  [[nodiscard]] const ConflictModel& conflicts() const { return conflicts_; }
  [[nodiscard]] int phase_count() const { return static_cast<int>(phases_.size()); }
  [[nodiscard]] const std::vector<LightState>& movement_states() const { return mstate_; }
  [[nodiscard]] const std::vector<WalkState>& crosswalk_states() const { return cwstate_; }

  // statistics
  [[nodiscard]] long switches() const { return switches_; }
  [[nodiscard]] const std::vector<double>& green_time() const { return green_time_; }
  [[nodiscard]] double clearance_time() const { return clearance_time_; }

  /// Pedestrian recall: re-display WALK for a crosswalk of the current green phase.
  /// Ignored unless the crosswalk is resting in DONT WALK and the extra walk +
  /// clearance fits before max-green. A phase change is deferred until it completes.
  void request_walk(int crosswalk);
  [[nodiscard]] bool pedestrian_interval_active() const;

  /// Runtime timing edits (validated: min <= max, values positive).
  bool set_phase_timing(int phase, double min_green, double max_green, std::string* error);

  /// True if no two conflicting movements are green/yellow and no WALK crosswalk
  /// conflicts with a green/yellow movement.
  [[nodiscard]] bool invariants_hold(std::string* why = nullptr) const;

 private:
  void begin_change(int target);
  void refresh_states();

  NodeId node_;
  ConflictModel conflicts_;
  std::vector<SignalPhase> phases_;
  int current_ = 0;
  int next_ = 0;
  SignalStage stage_ = SignalStage::Green;
  double t_stage_ = 0.0;
  std::vector<LightState> mstate_;  // indexed by local movement index
  std::vector<WalkState> cwstate_;
  std::vector<double> walk_start_;  // per crosswalk: stage time WALK began (-1 = not in this green)
  long switches_ = 0;
  std::vector<double> green_time_;
  double clearance_time_ = 0.0;
};

}  // namespace traffic
